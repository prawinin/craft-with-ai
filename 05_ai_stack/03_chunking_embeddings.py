# === COMMON MISTAKES ==========================================================

# MISTAKE 1: Naive character-count splitting cutting words in half
#   If you split strictly every 500 characters, you will split words (like "FastAPI"
#   becoming "Fast" in chunk 1 and "API" in chunk 2).
#   Use Recursive Character splitting which splits by double newlines (`\n\n`),
#   single newlines (`\n`), spaces (` `), and finally individual characters.

# MISTAKE 2: Storing embeddings as raw text arrays in standard databases
#   Running Cosine Similarity queries across millions of rows in a traditional SQL
#   database is incredibly slow. Always use dedicated Vector Databases (like ChromaDB,
#   Pinecone, or pgvector) that utilize HNSW indexing for millisecond lookups.

# MISTAKE 3: Neglecting chunk overlap context
#   Without overlap, boundary pronouns (e.g., "It resolves conflicts.") are separated
#   from their noun subjects ("Git") in preceding chunks, causing retrieval errors.
#   Always keep a 10% to 20% overlap window.


