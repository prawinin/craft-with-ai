# === CHUNKING STRATEGIES & OVERLAP ==========================================
#
# WHAT IS CHUNKING AND SEMANTIC SIMILARITY?
#   - Chunking is the process of slicing a long book or document into smaller, bite-sized paragraphs (chunks).
#     This ensures the text fits into the AI's short-term memory (context window) and prevents important facts
#     from getting lost in a sea of words.
#     (Context Window explained in Module 2, Lesson 4 — "Context-Driven AI")
#   - Semantic Similarity is a measure of how close two concepts are in meaning, regardless of whether they
#     use the exact same words. For example, "feline companion" and "pet cat" have high semantic similarity
#     even though they share zero letters!
#
# Slicing documents into chunks is a balancing act:
#   - If chunks are too small (e.g. 10 characters), they lose context.
#   - If chunks are too large (e.g. 50,000 characters), they dilute the meaning.
#
# Chunk Overlap:
#   We keep a small overlap (e.g. 10-20%) between consecutive chunks. This ensures
#   that a sentence cut in half at a boundary is preserved in full in the adjacent chunk.

# print("\n--- 2. CHUNKING WITH OVERLAP WINDOW ---")

def simulate_character_chunking(text, chunk_size=60, chunk_overlap=15):
    chunks = []
    start = 0
    
    while start < len(text):
        end = min(start + chunk_size, len(text))
        chunk = text[start:end]
        chunks.append((start, end, chunk))
        
        # Shift start forward by chunk_size minus overlap
        # This creates the overlapping window!
        start += (chunk_size - chunk_overlap)
        
        # Safety break if we aren't moving forward
        if chunk_size <= chunk_overlap:
            break
            
    return chunks

sample_manual = (
    "Retrieval-Augmented Generation (RAG) is a technique that grounds "
    "large language models on private datasets. It prevents hallucinations "
    "by supplying real document snippets as prompts context."
)

manual_chunks = simulate_character_chunking(sample_manual, chunk_size=80, chunk_overlap=20)
print(f"Original Text Length: {len(sample_manual)} characters.")
print(f"Generated {len(manual_chunks)} overlapping chunks:")
for idx, (s, e, text_val) in enumerate(manual_chunks, start=1):
    print(f"  Chunk #{idx} (Char {s}-{e}): '{text_val}'")


# === MATHEMATICAL COSINE SIMILARITY IN PYTHON ================================
#
# WHAT IS COSINE SIMILARITY?
#   Cosine Similarity is the mathematical tool we use to measure how close two vector coordinates are
#   on our language galaxy map. Instead of measuring the straight-line distance, it measures the ANGLE
#   between the two coordinate lines pointing from the center of the map. If the angle is 0 degrees, the
#   cosine is 1.0, meaning the two text snippets point in the exact same direction and share the same meaning!
#
# How do we measure the closeness of two vectors? We calculate the cosine of the
# angle between them.
#   - Cosine Similarity = 1.0  -> Vectors point in the exact same direction (Identical meaning).
#   - Cosine Similarity = 0.0  -> Vectors are orthogonal (No relationship).
#   - Cosine Similarity = -1.0 -> Vectors point in opposite directions.
#
# Formula: (A • B) / (||A|| * ||B||)
#   Where A • B is the dot product, and ||A|| is the magnitude.

# print("\n--- 3. CALCULATING SEMANTIC SIMILARITY ---")

def dot_product(v1, v2):
    return sum(x * y for x, y in zip(v1, v2))

def magnitude(v):
    return math.sqrt(sum(x * x for x in v))

def cosine_similarity(v1, v2):
    mag1 = magnitude(v1)
    mag2 = magnitude(v2)
    if mag1 == 0 or mag2 == 0:
        return 0.0
    return dot_product(v1, v2) / (mag1 * mag2)

# Let's define mock embeddings for three prompts:
#   v_query   = "How do I build a backend API in Python?"
#   v_target1 = "FastAPI is a modern web framework for Python routers."
#   v_target2 = "Making homemade apple pie requires baking apples and flour."

v_query   = [0.90, 0.85, 0.05]
v_target1 = [0.88, 0.82, 0.08] # Semantically close to query (high first/second coords)
v_target2 = [0.02, 0.10, 0.95] # Semantically unrelated to query (high third coord)

sim_api = cosine_similarity(v_query, v_target1)
sim_pie = cosine_similarity(v_query, v_target2)

print(f"Cosine Similarity (Query vs FastAPI Tech Doc): {sim_api:.4f} (Highly Relevant!)")
print(f"Cosine Similarity (Query vs Apple Pie Recipe):  {sim_pie:.4f} (Unrelated)")


