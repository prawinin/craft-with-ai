# === WHAT ARE VECTOR EMBEDDINGS? ============================================
#
# WHAT IS AN EMBEDDING AND A VECTOR?
#   - A Vector is simply a long list of numbers representing coordinates (like a GPS coordinate, but instead
#     of just 2 numbers for Latitude/Longitude, a vector might have 1,536 dimensions!).
#   - An Embedding is the vector coordinate that a specialized model generates to represent the MEANING of
#     a piece of text. Think of it like taking a word and finding its exact coordinate position on a giant
#     "galaxy map" of human language. Words that mean similar things are placed on neighboring planets,
#     while completely different words are in entirely separate solar systems!
#
# A vector embedding is a list of floating-point numbers (an array) generated by
# a specialized model (like OpenAI's text-embedding-ada-002).
#
# The Magic of Embeddings:
#   - Semantic meaning is converted to geometric coordinates.
#   - Words with similar meanings (e.g. "king" and "queen") are positioned close
#     to each other in high-dimensional space.
#   - Words with different meanings (e.g. "apple" and "database") are far apart.

